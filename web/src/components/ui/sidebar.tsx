const SIDEBAR_WIDTH = "264px"
const SIDEBAR_WIDTH_ICON = "52px"

type SidebarContext = {
  state: "expanded" | "collapsed"
  open: boolean
  setOpen: (open: boolean) => void
  toggleSidebar: () => void
}

const SidebarContext = React.createContext<SidebarContext | null>(null)

function useSidebar() {
  const context = React.useContext(SidebarContext)
  if (!context) {
    return { state: "expanded" as const, open: true, setOpen: () => {}, toggleSidebar: () => {} }
  }
  return context
}

function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  className,
  style,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  defaultOpen?: boolean
  open?: boolean
  onOpenChange?: (open: boolean) => void
}) {
  const [openState, setOpenState] = React.useState(defaultOpen)

  const open = openProp ?? openState
  const setOpen = React.useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const newState = typeof value === "function" ? value(open) : value
      setOpenProp?.(newState)
      setOpenState(newState)
    },
    [open, setOpenProp]
  )

  const toggleSidebar = React.useCallback(() => setOpen(!open), [open, setOpen])

  const state = open ? "expanded" : "collapsed"

  const contextValue = React.useMemo<SidebarContext>(
    () => ({ state, open, setOpen, toggleSidebar }),
    [open, setOpen, toggleSidebar, state]
  )

  return (
    <SidebarContext.Provider value={contextValue}>
      <div
        data-slot="sidebar-wrapper"
        data-collapsible={state === "collapsed" ? "icon" : "offcanvas"}
        style={
          {
            "--sidebar-width": SIDEBAR_WIDTH,
            "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
            ...style,
          } as React.CSSProperties
        }
        className={cn(
          "group/sidebar-wrapper has-data-[variant=inset]:bg-sidebar flex min-h-svh w-full",
          className
        )}
        {...props}
      >
        {children}
      </div>
    </SidebarContext.Provider>
  )
}

function Sidebar({
  className,
  children,
  ...props
}: React.ComponentProps<"div">) {
  const { state } = useSidebar()
  return (
    <div
      data-slot="sidebar"
      data-state={state}
      className={cn(
        "bg-sidebar text-sidebar-foreground relative flex h-full shrink-0 flex-col",
        className
      )}
      {...props}
    >
      {children}
    </div>
  )
}

